 function normalize(lang) {
 if (w.NC_I18N && w.NC_I18N.normalize) return w.NC_I18N.normalize(lang);
 var c = String(lang || "en").trim();
 if (UI[c]) return c;
 return "en";
 }

 function ui(lang) {
 return UI[normalize(lang)] || UI.en;
 }

 function htmlLang(lang) {
 var code = normalize(lang);
 if (code === "zh-CN") return "zh-Hans";
 if (code === "zh-TW") return "zh-Hant";
 return code;
 }

 function tpl(str, map) {
 return String(str || "").replace(/\{(\w+)\}/g, function (_, k) {
 return map[k] != null ? map[k]: "";
 });
 }

 function localizePhrase(nameEn, lang) {
 var code = normalize(lang);
 if (!nameEn) return "";
 if (code === "en") return nameEn;
 if (code === "ru") {
 if (RU_TAG[nameEn]) return RU_TAG[nameEn];
 var low = String(nameEn).toLowerCase();
 for (var rk in RU_TAG) {
 if (Object.prototype.hasOwnProperty.call(RU_TAG, rk) && rk.toLowerCase() === low) {
 return RU_TAG[rk];
 }
 }
 }
 var parts = CHUNK_TR[code];
 if (!parts) return nameEn;
 var out = nameEn;
 for (var i = 0; i < CHUNK_EN.length; i++) {
 if (!parts[i]) continue;
 var re = new RegExp(CHUNK_EN[i].replace(/[.*+?^${}()|[\]\\]/g, "\\$&"), "gi");
 out = out.replace(re, parts[i]);
 }
 return out;
 }

 function localizeTag(tag, lang) {
 if (!tag) return "";
 var code = normalize(lang);
 var en = tag.nameEn || tag.name || tag.slug || "";
 if (code === "en") return en;
 if (code === "ru") {
 if (tag.name && /[\u0400-\u04FF]/.test(tag.name)) return tag.name;
 return RU_TAG[en] || localizePhrase(en, code) || en;
 }
 var tr = localizePhrase(en, code);
 return tr || en;
 }

 function localizeCategory(catKey, lang) {
 if (!catKey) return "";
 var code = normalize(lang);
 var row = CAT[catKey];
 if (!row) {
 var low = String(catKey).trim();
 row = CAT[low];
 if (!row) {
 for (var k in CAT) {
 if (Object.prototype.hasOwnProperty.call(CAT, k) && k.toLowerCase() === low.toLowerCase()) {
 row = CAT[k];
 break;
 }
 }
 }
 }
 if (row) return row[code] || row.en || catKey;
 if (code === "en") return catKey;
 return localizePhrase(catKey, code) || catKey;
 }

